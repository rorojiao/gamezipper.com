#!/bin/bash
# Generate homepage facts from the repository, never from wall-clock display text.
set -euo pipefail
cd "$(dirname "$0")/.."

CONTENT_PATHS=(index.html js/games-data.js ':(glob)*/index.html')
UPDATED_AT=$(git log -1 --format=%cI -- "${CONTENT_PATHS[@]}")
SOURCE_COMMIT=$(git log -1 --format=%H -- "${CONTENT_PATHS[@]}")
if [ -z "$UPDATED_AT" ] || [ -z "$SOURCE_COMMIT" ]; then
  echo "Unable to resolve the last content commit" >&2
  exit 1
fi

DOW=$(date +%u)
WEEK_START=$(date -d "$(date +%F) -$((DOW - 1)) days" +%F)
NEW_GAMES=$(git log --since="$WEEK_START 00:00:00" --diff-filter=A --name-only --pretty=format: -- ':(glob)*/index.html' \
  | awk '/^[^/]+\/index\.html$/ { if (!seen[$0]++) count++ } END { print count + 0 }')

TMP=js/site-metadata.tmp.js
cat > "$TMP" <<EOF
// Generated by scripts/gen-site-metadata.sh from real git history. Do not hand-edit values.
window.GZ_SITE_META=Object.freeze({
  contentUpdatedAt:"$UPDATED_AT",
  newGamesThisWeek:$NEW_GAMES,
  sourceCommit:"$SOURCE_COMMIT",
  statsEndpoint:"https://bi.gamezipper.com/api/public-stats"
});
EOF
node --check "$TMP"
mv "$TMP" js/site-metadata.js
printf 'site metadata: updated=%s new_games_since_%s=%s source=%s\n' "$UPDATED_AT" "$WEEK_START" "$NEW_GAMES" "$SOURCE_COMMIT"
